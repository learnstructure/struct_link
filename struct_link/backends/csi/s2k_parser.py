"""
CSI (.s2k / .e2k) text table tokenizer, parser, and generator.

Handles both SAP2000 (.s2k / .$2k) and ETABS (.e2k / .$et) table-based text files.
"""

from __future__ import annotations

import re
import shlex
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple, Union


class S2kTable:
    """Represents a single named table from a CSI text file."""

    def __init__(self, name: str):
        self.name: str = name
        self.rows: List[Dict[str, Any]] = []

    def add_row(self, row: Dict[str, Any]) -> None:
        self.rows.append(row)

    def __repr__(self) -> str:
        return f"<S2kTable {self.name!r} ({len(self.rows)} rows)>"


class S2kParser:
    """Parser for CSI .s2k / .e2k text file formats."""

    # Regex to capture TABLE:  "TABLE NAME" or TABLE:  TABLE_NAME
    TABLE_START_RE = re.compile(r'^\s*TABLE:\s*"?([^"\r\n]+)"?', re.IGNORECASE)
    # Regex to parse Key=Value pairs, respecting quotes
    KV_PAIR_RE = re.compile(r'(\w+)\s*=\s*(?:"([^"]*)"|(\S+))')

    @classmethod
    def parse_file(cls, file_path: Union[str, Path]) -> Dict[str, S2kTable]:
        """Read and parse a CSI text file into a dictionary of S2kTable objects."""
        path = Path(file_path)
        with open(path, "r", encoding="utf-8", errors="replace") as f:
            content = f.read()
        return cls.parse_string(content)

    @classmethod
    def parse_string(cls, content: str) -> Dict[str, S2kTable]:
        """Parse raw text content of a CSI text file."""
        tables: Dict[str, S2kTable] = {}
        current_table: Optional[S2kTable] = None

        for line in content.splitlines():
            stripped = line.strip()
            if not stripped or stripped.startswith(";"):
                continue

            # Check for Table Header
            table_match = cls.TABLE_START_RE.match(stripped)
            if table_match:
                table_name = table_match.group(1).strip()
                current_table = S2kTable(table_name)
                tables[table_name.upper()] = current_table
                continue

            if stripped.upper() in ("END TABLE DATA", "END OF FILE"):
                current_table = None
                continue

            # If inside a table, parse key=value fields
            if current_table is not None:
                matches = cls.KV_PAIR_RE.findall(stripped)
                if matches:
                    row_data: Dict[str, Any] = {}
                    for key, quoted_val, unquoted_val in matches:
                        raw_val = quoted_val if quoted_val != "" else unquoted_val
                        # Type conversion helper
                        val: Any = raw_val
                        if raw_val.lower() in ("yes", "true"):
                            val = True
                        elif raw_val.lower() in ("no", "false"):
                            val = False
                        else:
                            try:
                                if "." in raw_val or "e" in raw_val.lower():
                                    val = float(raw_val)
                                else:
                                    val = int(raw_val)
                            except ValueError:
                                val = raw_val
                        row_data[key] = val

                    current_table.add_row(row_data)

        return tables


class S2kWriter:
    """Generator to serialize tables to standard CSI .s2k / .e2k text format."""

    @staticmethod
    def format_row(row: Dict[str, Any]) -> str:
        parts = []
        for k, v in row.items():
            if isinstance(v, bool):
                v_str = "Yes" if v else "No"
            elif isinstance(v, float):
                # Format float cleanly without trailing zeros if integer
                v_str = f"{v:.6g}"
            elif isinstance(v, str) and (" " in v or not v):
                v_str = f'"{v}"'
            else:
                v_str = str(v)
            parts.append(f"{k}={v_str}")
        return "   " + "   ".join(parts)

    @classmethod
    def write_tables(cls, tables: Dict[str, List[Dict[str, Any]]], output_path: Union[str, Path]) -> Path:
        """Write dictionary of tables to file."""
        path = Path(output_path)
        path.parent.mkdir(parents=True, exist_ok=True)
        lines = [
            "; CSI Text Data File",
            "; Generated by struct_link",
            "",
        ]

        for table_name, rows in tables.items():
            if not rows:
                continue
            lines.append(f'TABLE:  "{table_name}"')
            for row in rows:
                lines.append(cls.format_row(row))
            lines.append("")

        lines.append("END TABLE DATA")
        lines.append("")

        with open(path, "w", encoding="utf-8") as f:
            f.write("\n".join(lines))

        return path
